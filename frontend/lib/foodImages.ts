export const DEFAULT_IMAGE =
  "https://images.pexels.com/photos/1640777/pexels-photo-1640777.jpeg?auto=compress&w=400";

export function matchFoodImage(name: string): string {
  const lower = name.toLowerCase();

  // Try to match longest/most specific keyword first
  const sorted = [...foodImageMap].sort(
    (a, b) =>
      Math.max(...b.keywords.map((k) => k.length)) -
      Math.max(...a.keywords.map((k) => k.length))
  );

  for (const item of sorted) {
    if (item.keywords.some((k) => lower.includes(k))) {
      return item.url;
    }
  }

  return DEFAULT_IMAGE;
}